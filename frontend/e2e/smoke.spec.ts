import { expect, test } from '@playwright/test'
test('main page has three cards and working test and history actions', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.home-grid > .home-card')).toHaveCount(3)
  await expect(page.getByRole('heading', { name: 'Left & right hand', exact: true })).toBeVisible()
  await expect(page.locator('.home-hand-chart .recharts-line')).toHaveCount(2)
  await expect(page.getByRole('heading', { name: 'Daily check-in', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Your movement check', exact: true })).toBeVisible()
  await expect(page.getByText('Overview', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Private by design', { exact: true })).toHaveCount(0)
  await expect(page.locator('body')).not.toContainText(/waiting.*backend/i)
  await page.getByRole('link', { name: 'Start a movement check', exact: true }).click()
  await expect(page).toHaveURL(/\/check\/connect$/)
  await page.getByRole('link', { name: 'Back to home', exact: true }).click()
  await page.getByRole('link', { name: 'View history', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your check history', exact: true })).toBeVisible()
  const fourteen = await page.locator('tbody tr').count()
  await page.getByRole('button', { name: '7 days', exact: true }).click()
  expect(await page.locator('tbody tr').count()).toBeLessThan(fourteen)
})
test('preferences and local profile save and reopen', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Preferred hand').selectOption('left')
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click()
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Alex')
  await page.getByLabel('Email', { exact: true }).fill('alex@example.com')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Alex', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Alex', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByLabel('Preferred hand')).toHaveValue('left')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
